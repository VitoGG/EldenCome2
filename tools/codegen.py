"""Generate mod/src/generated.rs from the sheets. One row -> one struct literal.

Refuses to run while preflight has BLOCKING findings.
usage: python -I tools/codegen.py
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHEETS = ROOT / "sheets"
OUT = ROOT / "mod" / "src" / "generated.rs"


def load(name):
    return json.loads((SHEETS / f"{name}.json").read_text(encoding="utf-8"))["rows"]


def s(v):
    return json.dumps(v)  # Rust and JSON string escapes agree for our content


def strs(v):
    return "&[" + ", ".join(s(x) for x in v) + "]"


def f(v):
    v = float(v)
    return repr(v) if "." in repr(v) else repr(v) + ".0"


def main():
    pf = subprocess.run([sys.executable, "-I", str(ROOT / "tools" / "preflight.py")], capture_output=True, text=True)
    if pf.returncode != 0:
        print(pf.stdout)
        sys.exit("codegen: preflight has BLOCKING findings; fix the sheets first")

    o = ["// @generated by tools/codegen.py from sheets/*.json. Do not edit; change the sheet.",
         "#![allow(dead_code)]", ""]

    o += ["#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
          "pub enum SourceKind { XmlRows, XmlParams, Dds, FmodBank }", "",
          "#[derive(Debug)]",
          "pub struct Kcd2Source { pub id: &'static str, pub pak: &'static str, pub entry: &'static str, pub kind: SourceKind, pub element: &'static str, pub fields: &'static [&'static str], pub required: bool }",
          "pub const KCD2_SOURCES: &[Kcd2Source] = &["]
    kinds = {"xml_rows": "XmlRows", "xml_params": "XmlParams", "dds": "Dds", "fmod_bank": "FmodBank"}
    for r in load("kcd2_sources"):
        o.append(f"    Kcd2Source {{ id: {s(r['id'])}, pak: {s(r['pak'])}, entry: {s(r['entry'])}, kind: SourceKind::{kinds[r['kind']]}, element: {s(r['element'])}, fields: {strs(r['fields'])}, required: {str(r['required']).lower()} }},")
    o += ["];", ""]

    o += ["#[derive(Debug)]",
          "pub struct ZoneRow { pub kcd2_zone_id: i32, pub kcd2_name: &'static str, pub active: bool, pub label: &'static str }",
          "pub const ZONES: &[ZoneRow] = &["]
    for r in load("zones"):
        o.append(f"    ZoneRow {{ kcd2_zone_id: {r['kcd2_zone_id']}, kcd2_name: {s(r['kcd2_name'])}, active: {str(r['active']).lower()}, label: {s(r['label'])} }},")
    o += ["];", ""]

    o += ["#[derive(Debug)]",
          "pub struct AttackRow { pub id: &'static str, pub kcd2_attack_type: &'static str, pub input: &'static str, pub uses_zone: bool, pub stamina_scale: f32, pub buffer_s: f32 }",
          "pub const ATTACKS: &[AttackRow] = &["]
    for r in load("attacks"):
        o.append(f"    AttackRow {{ id: {s(r['id'])}, kcd2_attack_type: {s(r['kcd2_attack_type'])}, input: {s(r['input'])}, uses_zone: {str(r['uses_zone']).lower()}, stamina_scale: {f(r['stamina_scale'])}, buffer_s: {f(r['buffer_s'])} }},")
    o += ["];", ""]

    o += ["#[derive(Debug)]",
          "pub struct WeaponClassRow { pub id: &'static str, pub er_wep_type: u8, pub er_name: &'static str }",
          "pub const WEAPON_CLASSES: &[WeaponClassRow] = &["]
    for r in load("weapon_classes"):
        o.append(f"    WeaponClassRow {{ id: {s(r['id'])}, er_wep_type: {r['er_wep_type']}, er_name: {s(r['er_name'])} }},")
    o += ["];", ""]

    o += ["#[derive(Debug)]",
          "pub struct SwingRow { pub weapon_class: &'static str, pub attack: &'static str, pub kcd2_zone: &'static str, pub event_1h: &'static str, pub event_2h: &'static str }",
          "pub const SWING_MAP: &[SwingRow] = &["]
    for r in load("swing_map"):
        o.append(f"    SwingRow {{ weapon_class: {s(r['weapon_class'])}, attack: {s(r['attack'])}, kcd2_zone: {s(r['kcd2_zone'])}, event_1h: {s(r['event_1h'])}, event_2h: {s(r['event_2h'])} }},")
    o += ["];", ""]

    o += ["#[derive(Debug)]",
          "pub struct InputRow { pub id: &'static str, pub er_user_input: &'static [&'static str], pub kind: &'static str, pub suppress_for_game: bool }",
          "pub const INPUTS: &[InputRow] = &["]
    for r in load("inputs"):
        o.append(f"    InputRow {{ id: {s(r['id'])}, er_user_input: {strs(r['er_user_input'])}, kind: {s(r['kind'])}, suppress_for_game: {str(r['suppress_for_game']).lower()} }},")
    o += ["];", ""]

    o += ["#[derive(Debug)]",
          "pub struct DefenseRow { pub id: &'static str, pub er_mechanism: &'static str, pub sound: &'static str }",
          "pub const DEFENSE: &[DefenseRow] = &["]
    for r in load("defense"):
        o.append(f"    DefenseRow {{ id: {s(r['id'])}, er_mechanism: {s(r['er_mechanism'])}, sound: {s(r['sound'])} }},")
    o += ["];", ""]

    ed = {r["id"]: r["value"] for r in load("enemy_dirs")}
    o += ["// enemy_dirs",
          f"pub const ATTACK_ANIM_RANGE: (i32, i32) = ({ed['attack_anim_range'][0]}, {ed['attack_anim_range'][1]});",
          f"pub const TRACKED_BONES: &[&str] = {strs(ed['tracked_bones'])};",
          f"pub const DIRECTION_RULE: &str = {s(ed['direction_rule'])};",
          f"pub const ONSET_SPEED_MPS: f32 = {f(ed['onset_speed_mps'])};",
          f"pub const RECORD_S: f32 = {f(ed['record_s'])};",
          f"pub const LEARNED_TABLE: &str = {s(ed['learned_table'])};",
          f"pub const THRUST_RATIO: f32 = {f(ed['thrust_ratio'])};",
          f"pub const MIN_EXTENT_M: f32 = {f(ed['min_extent_m'])};",
          f"pub const SAMPLE_RATE_HZ: f32 = {f(ed['sample_rate_hz'])};",
          f"pub const FALLBACK_NO_BONE: &str = {s(ed['fallback_no_bone'])};", ""]

    o += ["#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
          "pub enum Anchor { ScreenCenter, LockedTarget }", "",
          "#[derive(Debug)]",
          "pub struct HudRow { pub id: &'static str, pub anchor: Anchor, pub icon: Option<&'static str>, pub size_px: f32 }",
          "pub const HUD: &[HudRow] = &["]
    anchors = {"screen_center": "ScreenCenter", "locked_target": "LockedTarget"}
    for r in load("hud"):
        icon = "None" if r["icon"] == "-" else f"Some({s(r['icon'])})"
        o.append(f"    HudRow {{ id: {s(r['id'])}, anchor: Anchor::{anchors[r['anchor']]}, icon: {icon}, size_px: {f(r['size_px'])} }},")
    o += ["];", ""]

    o += ["#[derive(Debug)]",
          "pub struct SoundRow { pub id: &'static str, pub source: &'static str, pub samples: &'static [&'static str], pub volume: f32 }",
          "pub const SOUNDS: &[SoundRow] = &["]
    for r in load("sounds"):
        o.append(f"    SoundRow {{ id: {s(r['id'])}, source: {s(r['source'])}, samples: {strs(r['samples'])}, volume: {f(r['volume'])} }},")
    o += ["];", ""]

    o += ["/// hooks sheet ids, used as log tags (`[hook:<id>]`) so each row's evidence is greppable.",
          "pub const HOOK_IDS: &[&str] = " + strs([r["id"] for r in load("hooks")]) + ";", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(o), encoding="utf-8")
    print(f"codegen: wrote {OUT.relative_to(ROOT)} ({len(o)} lines)")


if __name__ == "__main__":
    main()
